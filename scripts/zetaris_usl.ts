// Build and exercise the Zetaris Unified Semantic Layer, saving the results as evidence.
//
//   npm run zetaris:usl            # run every zetaris/sql/*.sql in order
//   npm run zetaris:usl -- 4 5     # run only the files whose names start with 4 or 5
//
// Each file runs on one JDBC session (scripts/ZetarisJson.java), and its statements and
// results are written to zetaris/results/<file>.md. Statements end with ";" at the end of a
// line, except COMPILE USL, which takes the rest of its file (its DDL contains semicolons).
// A statement after a "-- @ignore-error" line may fail without failing the run (cleanup
// before a rebuild). Needs Zetaris running and the datasets loaded (scripts/load_to_zetaris.sh).

import { spawn } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, loadDotEnv, zetarisSettings } from "../src/config.ts";

const SQL_DIR = join(ROOT, "zetaris", "sql");
const OUT_DIR = join(ROOT, "zetaris", "results");
const MAX_ROWS = 40;
const MAX_CELL = 90;

interface Statement {
  sql: string;
  comment: string;
  ignoreError: boolean;
}

type Result = { columns: string[]; rows: (string | null)[][] } | { error: string };

export function splitStatements(text: string): Statement[] {
  const out: Statement[] = [];
  let comment: string[] = [];
  let ignoreError = false;
  let body: string[] = [];
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!body.length) {
      if (/^\s*--\s*@ignore-error/.test(line)) { ignoreError = true; continue; }
      if (/^\s*--/.test(line)) { comment.push(line.replace(/^\s*--\s?/, "")); continue; }
      if (!line.trim()) { comment = []; continue; }
      if (/^\s*COMPILE\s/i.test(line)) {
        out.push({ sql: lines.slice(i).join("\n").trim(), comment: comment.join(" "), ignoreError });
        break;
      }
    }
    body.push(line);
    if (/;\s*$/.test(line)) {
      out.push({ sql: body.join("\n").trim().replace(/;$/, ""), comment: comment.join(" "), ignoreError });
      body = [];
      comment = [];
      ignoreError = false;
    }
  }
  if (body.join("").trim()) out.push({ sql: body.join("\n").trim(), comment: comment.join(" "), ignoreError });
  return out;
}

function run(statements: string[]): Promise<Result[]> {
  const z = zetarisSettings();
  if (!z) throw new Error("Zetaris isn't set up: set ZETARIS_DIR to your zetaris-platform folder (see README).");
  return new Promise((resolve, reject) => {
    const child = spawn("java", ["-cp", z.jar, join(ROOT, "scripts", "ZetarisJson.java"), ...statements], {
      env: { ...process.env, ZETARIS_URL: z.url, ZETARIS_USER: z.user, ZETARIS_PASSWORD: z.password },
      windowsHide: true,
    });
    let out = "";
    child.stdout.on("data", (d) => (out += d));
    child.on("error", reject);
    child.on("close", () => {
      const parsed = out.split(/\r?\n/).filter((l) => l.startsWith("{")).map((l) => JSON.parse(l));
      const fatal = parsed.find((p) => p.fatal);
      if (fatal) return reject(new Error(`Zetaris: ${fatal.fatal}`));
      resolve(parsed);
    });
  });
}

const cell = (v: string | null) => {
  const s = v === null ? "NULL" : v.replace(/\s+/g, " ").replace(/\|/g, "\\|");
  return s.length > MAX_CELL ? s.slice(0, MAX_CELL - 1) + "…" : s;
};

function markdown(file: string, statements: Statement[], results: Result[]): string {
  const parts = [`# ${file}\n\nGenerated by \`npm run zetaris:usl\` on ${new Date().toISOString().slice(0, 10)} against a live Zetaris instance. Source: [\`zetaris/sql/${file}\`](../sql/${file}).\n`];
  statements.forEach((s, i) => {
    const r = results[i];
    if (s.comment) parts.push(`## ${s.comment}\n`);
    parts.push("```sql\n" + s.sql + "\n```\n");
    if (!r) parts.push("_Not run (an earlier statement ended the session)._\n");
    else if ("error" in r) parts.push(`${s.ignoreError ? "Expected during cleanup" : "**Error**"}: \`${r.error.split("\n")[0]}\`\n`);
    else if (!r.columns.length) parts.push("_OK, no result set._\n");
    else {
      const rows = r.rows.slice(0, MAX_ROWS);
      parts.push(
        [`| ${r.columns.map(cell).join(" | ")} |`, `|${r.columns.map(() => "---").join("|")}|`, ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`)].join("\n") +
          `\n\n_${r.rows.length} row${r.rows.length === 1 ? "" : "s"}${r.rows.length > MAX_ROWS ? `, first ${MAX_ROWS} shown` : ""}._\n`,
      );
    }
  });
  return parts.join("\n");
}

async function main() {
  loadDotEnv();
  const only = process.argv.slice(2);
  const files = readdirSync(SQL_DIR).filter((f) => f.endsWith(".sql") && (!only.length || only.some((p) => f.startsWith(p)))).sort();
  mkdirSync(OUT_DIR, { recursive: true });
  let failed = 0;
  for (const file of files) {
    const statements = splitStatements(readFileSync(join(SQL_DIR, file), "utf-8"));
    process.stdout.write(`${file}: ${statements.length} statements ... `);
    const results = await run(statements.map((s) => s.sql));
    const errors = statements.filter((s, i) => !s.ignoreError && (!results[i] || "error" in results[i]));
    failed += errors.length;
    writeFileSync(join(OUT_DIR, file.replace(/\.sql$/, ".md")), markdown(file, statements, results));
    console.log(errors.length ? `${errors.length} failed` : "ok");
    for (const s of errors) {
      const r = results[statements.indexOf(s)];
      console.log(`  ${s.sql.split("\n")[0]}\n    ${r && "error" in r ? r.error.split("\n")[0] : "not run"}`);
    }
  }
  console.log(`Results in zetaris/results/.`);
  if (failed) process.exit(1);
}

if (import.meta.main) await main();
